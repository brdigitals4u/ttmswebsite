#!/usr/bin/env node

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  cleanPathFromLegacy,
  findHtmlFiles,
  legacyPathFromFile,
  toPosix
} from "./lib/route-utils.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const DIST_DIR = path.join(ROOT, "dist");
const REDIRECTS_DIR = path.join(ROOT, "deploy", "redirects");
const NGINX_DIR = path.join(ROOT, "deploy", "nginx");
const REDIRECTS_JSON_PATH = path.join(REDIRECTS_DIR, "legacy-map.json");
const NGINX_REDIRECTS_PATH = path.join(NGINX_DIR, "legacy-redirects.conf");

function buildRedirect(legacyPath) {
  return {
    from: legacyPath,
    to: cleanPathFromLegacy(legacyPath),
    status: 308
  };
}

function toNginxLocation(fromPath, toPath) {
  return `location = ${fromPath} { return 308 ${toPath}; }`;
}

const EXTRA_REDIRECTS = [
  { from: "/company/contact", to: "/contact/", status: 308 },
  { from: "/company/contact/", to: "/contact/", status: 308 },
  { from: "/blog/blog-alt-1/blog-detail.html", to: "/blog/blog-detail/", status: 308 },
  { from: "/blog/blog-alt-2/blog-detail.html", to: "/blog/blog-detail/", status: 308 }
];

async function main() {
  const htmlFiles = await findHtmlFiles(DIST_DIR);
  const redirects = [];

  for (const absPath of htmlFiles) {
    const rel = toPosix(path.relative(DIST_DIR, absPath));
    if (rel.startsWith("_templates/")) {
      continue;
    }

    const legacyPath = legacyPathFromFile(DIST_DIR, absPath);
    redirects.push(buildRedirect(legacyPath));
  }

  redirects.push(...EXTRA_REDIRECTS);
  const deduped = new Map();
  for (const redirect of redirects) {
    deduped.set(redirect.from, redirect);
  }

  const finalRedirects = [...deduped.values()];
  finalRedirects.sort((a, b) => a.from.localeCompare(b.from));

  await mkdir(REDIRECTS_DIR, { recursive: true });
  await mkdir(NGINX_DIR, { recursive: true });

  await writeFile(REDIRECTS_JSON_PATH, `${JSON.stringify(finalRedirects, null, 2)}\n`, "utf8");

  const nginxLines = [
    "# Auto-generated by scripts/generate-redirect-map.mjs",
    "# Legacy HTML routes -> clean URLs",
    ...finalRedirects.map((item) => toNginxLocation(item.from, item.to))
  ];

  await writeFile(NGINX_REDIRECTS_PATH, `${nginxLines.join("\n")}\n`, "utf8");

  process.stdout.write(
    `Generated ${finalRedirects.length} redirects: ${path.relative(ROOT, REDIRECTS_JSON_PATH)} and ${path.relative(
      ROOT,
      NGINX_REDIRECTS_PATH
    )}\n`
  );
}

main().catch((error) => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exit(1);
});
